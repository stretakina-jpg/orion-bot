export function getInitialLocale(): Locale {
  try {
    const saved = localStorage.getItem(LOCALE_KEY);
    if (saved === 'pt' || saved === 'en' || saved === 'es') return saved;
  } catch {}
  if (typeof navigator !== 'undefined') {
    const lang = (navigator.language || '').toLowerCase();
    if (lang.startsWith('es')) return 'es';
    if (lang.startsWith('en')) return 'en';
  }
  return 'pt';
}

let currentLocale: Locale = getInitialLocale();
const listeners = new Set<(loc: Locale) => void>();

export function setAppLocale(loc: Locale) {
  currentLocale = loc;
  try {
    localStorage.setItem(LOCALE_KEY, loc);
  } catch {}
  listeners.forEach((fn) => fn(loc));
}

export function useI18n() {
  const [locale, setLocaleState] = useState<Locale>(currentLocale);

  useEffect(() => {
    const listener = (loc: Locale) => setLocaleState(loc);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);

  const t = (key: string): string => {
    const dict = translations[locale] || translations.pt;
    return dict[key] || key;
  };

  const changeLocale = (loc: Locale) => {
    setAppLocale(loc);
  };

  return { locale, t, changeLocale };
}
